create or replace procedure aumento_stipendi_per_ruolo(
	p_min_stipendio numeric,
	p_ruolo varchar(100)
	)
	language plpgsql
	as $$
	begin
		update contratto
			set stipendio = stipendio * 1.10
			where stipendio > p_min_stipendio
				and id_contratto in (
					select con.id_contratto from contratto con
						join ruole r on con.id_ruole = r.id_ruole
							where lower(r.descrizione) = lower(p_ruolo) 
				);	
	end;
	$$
	
call aumento_stipendi_per_ruolo(1300, 'svilupatore')

