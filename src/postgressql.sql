/*
 * loop while
 *      exit  per uscire del while
 * 		continue rimane nel loop però salta il process
 * 		raise notice per avere un log
 */
create or replace procedure create_sp_employee(number_emp numeric)
language plpgsql
as $$
declare
	startPay numeric := 36000;
	emp_num numeric  := 0;
begin
	while (startPay < 200000) loop
		emp_num := emp_num + 1;
		if emp_num = number_emp then
			exit;
		end if;
		
		if emp_num % 2 = 0 then
			continue;
		end if;
		raise notice 'emp_id %', emp_num;

		insert into sp_employee (annual_salary) values (startPay);
		startPay := startPay + 5000;
	end loop;
end;
$$

call create_sp_employee(20);
