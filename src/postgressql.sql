drop function find_employees_simple;
create or replace function find_employees_sample(stipendio_min numeric)
	returns table (
		id int,
		fullname varchar(50),
		data_assunzione Date,
		stipendio numeric,
		descrizione varchar(100),
		tipo varchar(100)
	) as $$
	begin
		return QUERY
		select e.id , e.fullname , c.data_assunzione , c.stipendio , r.descrizione ,
		c2.tipo    from employee e
		left join contratto c on c.id_contratto = e.id_contratto 
		left join categoria c2 on c2.id_categoria  = c.id_categoria 
		left join ruole r  on r.id_ruole = c.id_ruole	
		where c.stipendio > stipendio_min;
	end;
	$$ language plpgsql;
	
