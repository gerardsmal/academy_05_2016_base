	returns trigger
	as $$
	begin
		if TG_OP = 'DELETE' then
			 INSERT INTO contratto_log(id_contratto,id_categoria,id_ruolo,stipendio,data_assunzione,data_dimisione,azione)
        	 VALUES (OLD.id_contratto,OLD.id_categoria,OLD.id_ruole,OLD.stipendio,OLD.data_assunzione,OLD.data_dimisione,TG_OP);
			 return old;
		else 
			INSERT INTO contratto_log(id_contratto,id_categoria,id_ruolo,stipendio,data_assunzione,data_dimisione,azione)
        	 VALUES (new.id_contratto,new.id_categoria,new.id_ruole,new.stipendio,new.data_assunzione,new.data_dimisione,TG_OP); 
			return new;
		end if;
	end;
	$$ language plpgsql;	

